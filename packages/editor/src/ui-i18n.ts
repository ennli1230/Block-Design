/** Stable callback keys are generated as `ui.<normalized-source-text>`. */
export function uiTextKey(source: string): string {
  const slug = source.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[ıİ]/g, 'i').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return `ui.${slug || 'label'}`;
}

export function resolveUiText(
  source: string,
  locale: string,
  override?: (key: string, locale: string) => string | undefined,
): string {
  const custom = override?.(uiTextKey(source), locale);
  if (custom !== undefined) return custom;
  return locale.toLowerCase().startsWith('en') ? englishText[source] ?? englishMessages[source] ?? source : source;
}

export function hasEnglishUiText(source: string): boolean {
  return Object.hasOwn(englishText, source) || Object.hasOwn(englishMessages, source);
}

export function useUiText(): UiText {
  return inject(uiTextInjectionKey, (source) => source);
}
